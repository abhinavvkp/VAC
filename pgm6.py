import pandas as pd
df=pd.read_csv("pgm6.csv")
print("sales dataset:")
print(df)
print("\nmean:")
print(df[["advertisement","sales"]].mean())
print("\nmedian:")
print(df[["advertisement","sales"]].median())
print("\nmode:")
print(df[["advertisement","sales"]].mode())
print("\nvariance:")
print(df[["advertisement","sales"]].var())
print("\nstandard deviation:")
print(df[["advertisement","sales"]].std())
print("\ncorrelation between advertisement and sales:")
print(df["advertisement"].corr(df["sales"]))
